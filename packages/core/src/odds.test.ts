const QUINELLA_ROWS: Row[] = [
  ['2', '2.2', '', '', '', '', '', '', '', '', '', ''],
  ['3', '7.9', '3', '30.7', '', '', '', '', '', '', '', ''],
  ['4', '5.8', '4', '19.2', '4', '40.6', '', '', '', '', '', ''],
  ['5', '9.2', '5', '24.7', '5', '31.6', '5', '24.7', '', '', '', ''],
  ['6', '7.2', '6', '19.1', '6', '45.9', '6', '39.1', '6', '36.0', '', ''],
];

describe('2連複オッズ', () => {
  const odds = parsePairOdds(QUINELLA_ROWS, false);

  test('昇順に正規化された買い目になる', () => {
    assert.equal(odds['1=2'], 2.2);
    assert.equal(odds['1=3'], 7.9);
    assert.equal(odds['2=3'], 30.7);
    assert.equal(odds['5=6'], 36.0);
  });

  test('空セルは無視される', () => {
    assert.equal(Object.keys(odds).length, 15);
  });

  test('順不同なので 2=1 という形は生まれない', () => {
    assert.ok(!('2=1' in odds));
    assert.ok(!('3=1' in odds));
  });
});

