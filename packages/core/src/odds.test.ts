const WIN_ROWS: Row[] = [
  ['1', '磯部 誠', '1.2'],
  ['2', '丸野 一樹', '7.0'],
  ['3', '湯川 浩司', '13.5'],
  ['4', '吉田 裕平', '12.4'],
  ['5', '仲谷 颯仁', '10.5'],
  ['6', '馬場 貴也', '8.1'],
];

const PLACE_ROWS: Row[] = [
  ['1', '磯部 誠', '1.0-1.0'],
  ['2', '丸野 一樹', '1.3-2.3'],
  ['3', '湯川 浩司', '4.5-8.6'],
  ['4', '吉田 裕平', '3.3-6.3'],
  ['5', '仲谷 颯仁', '2.8-5.3'],
  ['6', '馬場 貴也', '1.8-3.4'],
];

describe('単勝オッズ', () => {
  const odds = parseWinOdds(WIN_ROWS);

  test('艇番ごとの倍率が取れる', () => {
    assert.equal(odds['1'], 1.2);
    assert.equal(odds['3'], 13.5);
    assert.equal(odds['6'], 8.1);
    assert.equal(Object.keys(odds).length, 6);
  });

  test('選手名は倍率として拾われない', () => {
    assert.ok(Object.values(odds).every((v) => Number.isFinite(v)));
  });
});

describe('複勝オッズ', () => {
  const odds = parsePlaceOdds(PLACE_ROWS);

  test('範囲表示から低いほうを採る', () => {
    assert.equal(odds['1'], 1.0);
    assert.equal(odds['2'], 1.3);
    assert.equal(odds['3'], 4.5);
    assert.equal(Object.keys(odds).length, 6);
  });
});

// ---------------------------------------------------------------------

describe('払戻見込み', () => {
  test('賭け点数 × 倍率、端数切り捨て', () => {
    assert.equal(estimatePayout(1000, 17.4), 17400);
    assert.equal(estimatePayout(100, 11.7), 1170);
    assert.equal(estimatePayout(300, 3.4), 1020);
    // 端数
    assert.equal(estimatePayout(100, 1.25), 125);
  });
});

// ---------------------------------------------------------------------

describe('壊れた入力に耐える', () => {
  test('空でも落ちない', () => {
    assert.deepEqual(parseTrifectaOdds([]), {});
    assert.deepEqual(parsePairOdds([], true), {});
    assert.deepEqual(parseWinOdds([]), {});
    assert.deepEqual(parsePlaceOdds([]), {});
  });

  test('列数が合わない行は3連単で無視される', () => {
    const odds = parseTrifectaOdds([['1', '2', '3.5']]);
    assert.deepEqual(odds, {});
  });

  test('欠場などで数字が入らないセルがあっても他は生きる', () => {
    const odds = parsePairOdds([['2', '欠場', '1', '9.8', '', '', '', '', '', '', '', '']], true);
    assert.equal(odds['2-1'], 9.8);
    assert.ok(!('1-2' in odds));
  });
});
