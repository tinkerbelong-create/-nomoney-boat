const EXACTA_ROWS: Row[] = [
  ['2', '3.4', '1', '9.8', '1', '34.9', '1', '29.7', '1', '25.2', '1', '36.9'],
  ['3', '8.7', '3', '52.6', '2', '68.2', '2', '45.8', '2', '35.7', '2', '52.7'],
  ['4', '6.7', '4', '41.7', '4', '69.7', '3', '83.1', '3', '52.5', '3', '92.5'],
  ['5', '12.8', '5', '52.2', '5', '70.7', '5', '47.4', '4', '43.0', '4', '86.9'],
  ['6', '8.8', '6', '35.6', '6', '81.3', '6', '77.3', '6', '49.7', '5', '90.2'],
];

describe('2連単オッズ', () => {
  const odds = parsePairOdds(EXACTA_ROWS, true);

  test('列の位置が1着、セルの数字が2着', () => {
    assert.equal(odds['1-2'], 3.4);
    assert.equal(odds['2-1'], 9.8);
    assert.equal(odds['3-1'], 34.9);
    assert.equal(odds['6-5'], 90.2);
  });

  test('順序が保たれる（1-2 と 2-1 は別物）', () => {
    assert.notEqual(odds['1-2'], odds['2-1']);
  });

  test('30通りすべて揃う', () => {
    assert.equal(Object.keys(odds).length, 30);
  });
});

