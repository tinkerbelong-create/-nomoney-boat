/**
 * オッズ解析の検証。
 *
 * 固定値は 2026-08-01 びわこ12R（第31回オーシャンカップ 準優勝戦）の
 * 公式オッズページから実際に取った値を使っている。
 */

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';

import {
  parseTrifectaOdds,
  parseTrioOdds,
  parsePairOdds,
  parseWinOdds,
  parsePlaceOdds,
  estimatePayout,
  type Row,
} from './odds.ts';

// ---------------------------------------------------------------------
// 3連単（実ページの先頭5行分。1列あたり20行のうち最初の5行）
//
// 各行は「2着 3着 オッズ」×6列。2着は4行に1度しか出ない（rowspan）。
// ---------------------------------------------------------------------

const TRIFECTA_ROWS: Row[] = [
  ['2', '3', '11.7', '1', '3', '29.4', '1', '2', '72.8', '1', '2', '70.6', '1', '2', '169.8', '1', '2', '87.0'],
  ['4', '10.2', '4', '24.0', '4', '121.5', '3', '163.1', '3', '284.0', '3', '243.5'],
  ['5', '17.4', '5', '43.0', '5', '133.0', '5', '123.9', '4', '306.2', '4', '225.1'],
  ['6', '11.7', '6', '27.3', '6', '143.5', '6', '113.4', '6', '230.3', '5', '282.9'],
  ['3', '2', '23.4', '3', '1', '72.9', '2', '1', '118.7', '2', '1', '120.6', '2', '1', '292.8', '2', '1', '117.6'],
];

describe('3連単オッズ', () => {
  const odds = parseTrifectaOdds(TRIFECTA_ROWS);

  test('1行目が各1着の先頭の買い目に対応する', () => {
    assert.equal(odds['1-2-3'], 11.7);
    assert.equal(odds['2-1-3'], 29.4);
    assert.equal(odds['3-1-2'], 72.8);
    assert.equal(odds['4-1-2'], 70.6);
    assert.equal(odds['5-1-2'], 169.8);
    assert.equal(odds['6-1-2'], 87.0);
  });

  test('2〜4行目は3着だけが変わる', () => {
    assert.equal(odds['1-2-4'], 10.2);
    assert.equal(odds['1-2-5'], 17.4);
    assert.equal(odds['1-2-6'], 11.7);
    assert.equal(odds['2-1-4'], 24.0);
    assert.equal(odds['6-1-5'], 282.9);
  });

  test('5行目で2着が繰り上がる', () => {
    assert.equal(odds['1-3-2'], 23.4);
    assert.equal(odds['2-3-1'], 72.9);
    assert.equal(odds['3-2-1'], 118.7);
  });

  test('rowspan で艇番が省略された行も正しく復元される', () => {
    // 2行目は数字が2個ずつしかない（2着が省略）が、
    // 小数だけを拾って位置で解釈するので影響を受けない
    assert.equal(odds['1-2-4'], 10.2);
  });
});

// ---------------------------------------------------------------------
// 3連複（実ページ全10行）
//
// 下三角。列0は10行、列1は6行（表の5行目から）、列2は3行（8行目から）、
// 列3は1行（10行目のみ）。合計20通り。
// ---------------------------------------------------------------------

const TRIO_ROWS: Row[] = [
  ['2', '3', '7.1'],
  ['4', '5.0'],
  ['5', '7.8'],
  ['6', '5.8'],
  ['3', '4', '13.0', '3', '4', '43.8'],
  ['5', '12.4', '5', '41.9'],
  ['6', '13.0', '6', '38.1'],
  ['4', '5', '12.2', '4', '5', '30.9', '4', '5', '49.6'],
  ['6', '12.8', '6', '28.7', '6', '66.2'],
  ['5', '6', '15.9', '5', '6', '33.8', '5', '6', '65.0', '5', '6', '44.8'],
];

describe('3連複オッズ', () => {
  const odds = parseTrioOdds(TRIO_ROWS);

  test('20通りすべて揃う', () => {
    assert.equal(Object.keys(odds).length, 20);
  });

  test('列0（軸=1）が正しく読める', () => {
    assert.equal(odds['1=2=3'], 7.1);
    assert.equal(odds['1=2=4'], 5.0);
    assert.equal(odds['1=2=5'], 7.8);
    assert.equal(odds['1=2=6'], 5.8);
    assert.equal(odds['1=3=4'], 13.0);
    assert.equal(odds['1=3=5'], 12.4);
    assert.equal(odds['1=4=5'], 12.2);
    assert.equal(odds['1=5=6'], 15.9);
  });

  test('列がずれて始まる分も正しく対応づく', () => {
    // 列1（軸=2）は表の5行目から始まる
    assert.equal(odds['2=3=4'], 43.8);
    assert.equal(odds['2=3=5'], 41.9);
    assert.equal(odds['2=4=6'], 28.7);
    assert.equal(odds['2=5=6'], 33.8);
    // 列2（軸=3）は8行目から
    assert.equal(odds['3=4=5'], 49.6);
    assert.equal(odds['3=4=6'], 66.2);
    assert.equal(odds['3=5=6'], 65.0);
    // 列3（軸=4）は最終行のみ
    assert.equal(odds['4=5=6'], 44.8);
  });

  test('すべて昇順に正規化されている', () => {
    for (const key of Object.keys(odds)) {
      const parts = key.split('=').map(Number);
      assert.deepEqual(parts, [...parts].sort((a, b) => a - b), `${key} が昇順でない`);
    }
  });

  test('3連単の買い目形式は混ざらない', () => {
    assert.ok(Object.keys(odds).every((k) => k.includes('=') && !k.includes('-')));
  });
});

