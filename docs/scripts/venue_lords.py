# ===================== 検証 =====================
import os
HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
import sys, os, collections

err = []
VENUES = {'01':'桐生','02':'戸田','03':'江戸川','04':'平和島','05':'多摩川','06':'浜名湖',
 '07':'蒲郡','08':'常滑','09':'津','10':'三国','11':'びわこ','12':'住之江','13':'尼崎',
 '14':'鳴門','15':'丸亀','16':'児島','17':'宮島','18':'徳山','19':'下関','20':'若松',
 '21':'芦屋','22':'福岡','23':'唐津','24':'大村'}

if len(LORDS) != 24: err.append(f'{len(LORDS)}体しかない（24体のはず）')
codes = [l[0] for l in LORDS]
if sorted(codes) != sorted(VENUES): err.append('場コードが24場と一致しない')
for c, name, *_ in [(l[0], l[1]) for l in LORDS]:
    if VENUES.get(c) != name: err.append(f'{c}: 場名が{name}になっている（正しくは{VENUES.get(c)}）')
names = [l[2] for l in LORDS]
d = [n for n, k in collections.Counter(names).items() if k > 1]
if d: err.append(f'主の名前が重複: {d}')

# 既存300種と衝突していないか
try:
    ns = {}
    exec(open(os.path.join(HERE, 'fish_species.py'), encoding='utf-8').read().split('# ===================== 検証')[0], ns)
    base = {n for lst in ns['SPECIES'].values() for n, _ in lst}
    hit = [n for n in names if n in base]
    if hit: err.append(f'300種リストと名前が衝突: {hit}')
    else: print(f'（300種リストとの衝突なし）')
except FileNotFoundError:
    print('（fish_species.py が見つからないので衝突チェックをスキップ）')

for l in LORDS:
    if not l[5]: err.append(f'{l[1]}: 由来が空')
    if len(l[6]) > 45: err.append(f'{l[1]}: 説明が長い（{len(l[6])}字）')

print('=' * 78)
print('検証:', '全項目パス' if not err else f'{len(err)}件')
for e in err: print('  NG', e)
print('=' * 78)
print()
for c, v, n, kj, cat, moto, desc in LORDS:
    print(f'{c} {v:<5} {n:<18}（{kj}）{cat:<4} ← {moto}')
    print(f'{"":>10}{desc}')
print()
print('カテゴリ内訳:', '  '.join(f'{k}{v}' for k, v in collections.Counter(l[4] for l in LORDS).most_common()))

