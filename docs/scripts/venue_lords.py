    sql = ("-- 自動生成: python3 docs/scripts/venue_lords.py --sql\n"
           "-- 24場の主。★10・その場でしか出ない。\n\n"
           "insert into fish (code, name, star, category, venue_code, description) values\n"
           + ',\n'.join(rows) + "\non conflict (code) do update set\n"
           "  name = excluded.name, category = excluded.category,\n"
           "  venue_code = excluded.venue_code, description = excluded.description;\n")
    open(os.path.join(DATA, 'venue_lords.sql'), 'w', encoding='utf-8').write(sql)
    print('\n→ docs/data/venue_lords.sql を書き出した')
