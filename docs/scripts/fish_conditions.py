# ===================== 検証 =====================
import os
HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
import collections, itertools

ns = {}
exec(open(os.path.join(HERE, 'fish_species.py'), encoding='utf-8').read().split('# ===================== 検証')[0], ns)
SPECIES = ns['SPECIES']
STAR = {n: s for s, lst in SPECIES.items() for n, _ in lst}
ALL = set(STAR)

err, assigned = [], {}
for cond, names in COND.items():
    for n in names:
        if n not in ALL: err.append(f'{cond}: 「{n}」は300種リストにない')
        elif n in assigned: err.append(f'「{n}」が {assigned[n]} と {cond} に重複')
        else: assigned[n] = cond
BASE = sorted(ALL - set(assigned), key=lambda n: (STAR[n], n))

def pool(venue, night, star):
    """そのレースで、その★のときに出うる種"""
    _, area, water = VENUE[venue]
    out = []
    for n in ALL:
        if STAR[n] != star: continue
        c = assigned.get(n, '')
        if c == '' \
           or c == f'水:{water}' \
           or c == f'地:{area}' \
           or (c == '時:夜' and night):
            out.append(n)
    return out

# 実在しうる組み合わせだけを検証する。
# 「夜のレースがない場」は 夜=False のケースしか起きないので、
# 夜=True/False の両方を回しておけば、どちらの運用でも穴が出ない。
worst = {}
for v in VENUE:
    # その場に実在する時間帯だけを見る。夜のレースがない場で夜を検証しても意味がない
    times = [False, True] if has_night(v) else [False]
    for nt in times:
        for s in range(1, 11):
            c = len(pool(v, nt, s))
            if c == 0:
                err.append(f'{VENUE[v][0]}/{"夜" if nt else "昼"} の★{s} に候補なし')
            if s not in worst or c < worst[s][0]:
                worst[s] = (c, f'{VENUE[v][0]}/{"夜" if nt else "昼"}')

# 開催時間帯マスタの整合：全24場がちょうど1つの区分に入るか
allv = [c for lst in VENUE_TIME.values() for c in lst]
if sorted(allv) != sorted(VENUE): err.append('VENUE_TIME が24場と一致しない')
if len(allv) != len(set(allv)):   err.append('VENUE_TIME に重複がある')

# 夜限定種は、ナイター7場でしか手に入らない。それを明示する
night_only = [n for n, c in assigned.items() if c == '時:夜']

print('=' * 74)
print('検証:', '全項目パス' if not err else f'{len(err)}件')
for e in err[:15]: print('  NG', e)
print('=' * 74)
print(f'\nベース {len(BASE)}種 ／ 条件つき {len(assigned)}種 ／ 計 {len(BASE)+len(assigned)}種\n')
for c, names in COND.items():
    ss = sorted(STAR[n] for n in names if n in STAR)
    print(f'  {c:<8}{len(names):>3}種  ★{ss[0]}〜★{ss[-1]}')
print(f'  {"ベース":<8}{len(BASE):>3}種  ★1〜★10')
print('\n★ごとのベース種数')
print('  ' + '  '.join(f'★{s}:{sum(1 for n in BASE if STAR[n]==s)}' for s in range(1, 11)))
print('\n候補数の最小値（全組み合わせ中の最悪ケース）')
print('  ' + '  '.join(f'★{s}:{worst[s][0]}' for s in range(1, 11)))
print('\n開催時間帯（2026-08 調べ・設計参考用。実行時は締切時刻で判定）')
for k, v in VENUE_TIME.items():
    print(f'  {k:<6}{len(v)}場  ' + '・'.join(VENUE[c][0] for c in v))
print(f'\n夜限定 {len(night_only)}種 は ナイター7場でしか出ない')
print(f'  {"・".join(sorted(night_only))}')
print(f'\n夜の差（大村・★9）  昼 {len(pool("24", False, 9))}候補 → 夜 {len(pool("24", True, 9))}候補')
