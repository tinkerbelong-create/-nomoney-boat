"""
300種に「どこで出るか」の条件を割り当てる。

【この版で変えたこと】
  旧版は「地区ごとに10種」のように枠を先に決めて数を埋めていた。
  その結果、ホタテガイを中国地区に、キビナゴを近畿地区に入れるような
  事実に反する割り当てが多数まぎれていた。

  この版では枠を先に決めない。
  根拠が言えるものだけに条件をつけ、言えないものは全部ベースに戻す。
  だから地区ごとの種類数はバラバラ（関東7・東海3…）。それでよい。
  関東が多いのは「江戸前」という文化が実在するからで、数の偏りには理由がある。

条件は1種につき1つだけ。ANDにはしない。

    水:*   生態で決まる。メダカは淡水、マサバは海水。根拠が最も強い
    地:*   その土地の名物として実在するものだけ
    時:夜  生態の根拠はない（深海は昼も暗い）。ナイターの演出として置く

【等級（SG/G1/G2/G3/一般）はここにない】
  等級限定の魚は廃止した。「キンメダイがG2でしか出ない」理由が自然界になく、
  説明できないため。等級は fish_rates.py 側で「★の出やすさ」を動かす役に回した。
  等級が上がると良い★が出やすくなるが、出る種類の顔ぶれは変わらない。

    python3 docs/scripts/fish_conditions.py
"""

