# ===================== 検証 =====================
import os
HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
import sys, os, collections, unicodedata

CATS = [F, K, S, T, J, E, W, C, M, O]
err = []

names = [n for lst in SPECIES.values() for n, _ in lst]
dups = [n for n, c in collections.Counter(names).items() if c > 1]
if dups: err.append(f'名前の重複: {dups}')

total = len(names)
if total != 300: err.append(f'合計が{total}種（300のはず）')

counts = {s: len(v) for s, v in SPECIES.items()}
for s in range(1, 10):
    if counts[s] < counts[s + 1]:
        err.append(f'★{s}({counts[s]}種) < ★{s+1}({counts[s+1]}種) — 上ほど少ないはず')

for s, lst in SPECIES.items():
    for n, c in lst:
        if c not in CATS: err.append(f'★{s} {n}: 未知のカテゴリ {c}')
        if not n or any(unicodedata.category(ch) == 'Zs' for ch in n):
            err.append(f'★{s} {n}: 名前に空白')

print('=' * 70)
print('検証:', '全項目パス' if not err else f'{len(err)}件')
for e in err: print('  NG', e)
print('=' * 70)
print(f'\n合計 {total}種\n')

print(f'{"★":<4}{"種類数":>7}{"割合":>8}   カテゴリ内訳')
print('-' * 70)
for s in range(1, 11):
    lst = SPECIES[s]
    cc = collections.Counter(c for _, c in lst)
    inner = ' '.join(f'{k}{v}' for k, v in sorted(cc.items(), key=lambda x: -x[1]))
    bar = '#' * round(len(lst) / 2)
    print(f'★{s:<3}{len(lst):>7}{len(lst)/total*100:>7.1f}%   {inner}')
print()

allc = collections.Counter(c for lst in SPECIES.values() for _, c in lst)
print('カテゴリ合計:', '  '.join(f'{k} {v}' for k, v in allc.most_common()))
print()

# ---- 出力 ----
if '--csv' in sys.argv:
    with open(os.path.join(DATA, 'fish_species.csv'), 'w', encoding='utf-8') as f:
        f.write('code,name,star,category\n')
        i = 0
        for s in range(1, 11):
            for n, c in SPECIES[s]:
                i += 1
                f.write(f'f{i:03d},{n},{s},{c}\n')
    print('→ docs/data/fish_species.csv を書き出した')

if '--sql' in sys.argv:
    rows, i = [], 0
    for s in range(1, 11):
        for n, c in SPECIES[s]:
            i += 1
            rows.append(f"  ('f{i:03d}', '{n}', {s}, '{c}')")
    body = ',\n'.join(rows)
    sql = ("-- 自動生成: python3 docs/scripts/fish_species.py --sql\n"
           "-- 手で編集しないこと。名前を変えるときは fish_species.py を直す。\n\n"
           "insert into fish (code, name, star, category) values\n"
           + body + "\non conflict (code) do update set\n"
           "  name = excluded.name, star = excluded.star, category = excluded.category;\n")
    with open(os.path.join(DATA, 'fish_species.sql'), 'w', encoding='utf-8') as f:
        f.write(sql)
    print('→ docs/data/fish_species.sql を書き出した')
